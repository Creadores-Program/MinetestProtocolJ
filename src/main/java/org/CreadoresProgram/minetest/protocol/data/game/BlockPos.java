package org.CreadoresProgram.minetest.protocol.data.game;
public class BlockPos{
    private short x, y, z;
    public BlockPos(short x, short y, short z){
        this.x = x;
        this.y = y;
        this.z = z;
    }
    public short getX(){
        return this.x;
    }
    public short getX(){
        return this.x;
    }
    public short getZ(){
        return this.z;
    }
}